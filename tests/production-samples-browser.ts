import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
import { mkdir } from "node:fs/promises";
import { chromium } from "playwright-core";
import { auth } from "../src/lib/auth";
import { prisma } from "../src/lib/prisma";

if (process.env.NEON_BRANCH !== "dev/blackfruit") throw new Error("Solo se permite dev/blackfruit.");
const baseUrl = process.env.QA_BASE_URL ?? "http://localhost:3000";

async function main() {
  const email = `feature-qa-${randomUUID()}@example.invalid`;
  const password = `${randomBytes(24).toString("base64url")}Aa1!`;
  const marker = randomUUID().slice(0, 8);
  let actorId = "";
  const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-webgl"] });
  const context = await browser.newContext({ viewport: { width: 1365, height: 920 } });
  const page = await context.newPage();
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  try {
    const user = await auth.api.createUser({ body: { email, password, name: "Feature QA", role: "admin", data: { emailVerified: true } } });
    actorId = user.user.id;
    const salesBefore = await prisma.sale.count();
    await page.goto(`${baseUrl}/login`);
    await page.getByLabel("Email").fill(email);
    await page.getByLabel("Contraseña").fill(password);
    await page.getByRole("button", { name: "Ingresar" }).click();
    await page.waitForURL("**/dashboard");

    await page.goto(`${baseUrl}/produccion/maquinas`);
    const form = page.getByRole("region", { name: "Agregar máquina" });
    const machineName = `Máquina ${marker}`;
    await form.getByLabel("Nombre").fill(machineName);
    await form.getByLabel("Cantidad de bandejas").fill("16");
    const machineBackDialog = page.waitForEvent("dialog").then(async (dialog) => { assert.match(dialog.message(), /máquina sin guardar/); await dialog.dismiss(); });
    await page.evaluate(() => window.history.back());
    await machineBackDialog;
    assert.equal(await form.getByLabel("Nombre").inputValue(), machineName);
    await form.getByRole("button", { name: "Agregar máquina" }).click();
    await page.getByRole("heading", { name: machineName }).waitFor();
    const secondName = `Máquina secundaria ${marker}`;
    await form.getByLabel("Nombre").fill(secondName);
    await form.getByRole("button", { name: "Agregar máquina" }).click();
    await page.getByRole("heading", { name: secondName }).waitFor();
    page.once("dialog", (dialog) => void dialog.accept());
    await page.getByRole("article").filter({ hasText: secondName }).getByRole("button", { name: "Eliminar si no tiene ciclos" }).click();
    await page.getByRole("heading", { name: secondName }).waitFor({ state: "hidden" });

    await page.goto(`${baseUrl}/produccion`);
    await page.getByRole("navigation", { name: "Secciones de producción" }).getByRole("link", { name: "Máquina" }).click();
    await page.waitForURL("**/produccion/maquina");
    await page.getByRole("region", { name: "Vista previa de la máquina" }).waitFor();
    await page.getByRole("button", { name: "Pantalla completa", exact: true }).waitFor();
    await page.getByText("Piezas visibles", { exact: true }).click();
    await page.getByRole("checkbox", { name: "Bandejas separadas" }).check();
    await page.getByRole("checkbox", { name: "Ver interior" }).check();
    assert.equal(await page.getByRole("checkbox", { name: "Pared derecha" }).isChecked(), false);

    await page.goto(`${baseUrl}/productos`);
    if (!(await page.locator("details").first().evaluate((element) => (element as HTMLDetailsElement).open))) await page.getByText("Agregar producto o variante").click();
    const orange = `Naranja ${marker}`;
    const apple = `Manzana ${marker}`;
    await page.getByLabel("Producto", { exact: true }).fill(orange);
    await page.getByLabel("Variante (opcional)").fill("Con azúcar");
    const productBackDialog = page.waitForEvent("dialog").then(async (dialog) => { assert.match(dialog.message(), /producto sin guardar/); await dialog.dismiss(); });
    await page.evaluate(() => window.history.back());
    await productBackDialog;
    assert.equal(await page.getByLabel("Producto", { exact: true }).inputValue(), orange);
    await page.getByRole("button", { name: "Agregar al catálogo" }).click();
    await page.getByRole("cell", { name: orange }).waitFor();
    if (!(await page.locator("details").first().evaluate((element) => (element as HTMLDetailsElement).open))) await page.getByText("Agregar producto o variante").click();
    await page.getByLabel("Producto", { exact: true }).fill(apple);
    await page.getByRole("button", { name: "Agregar al catálogo" }).click();
    await page.getByRole("cell", { name: apple }).waitFor();
    await page.goto(`${baseUrl}/productos?q=${encodeURIComponent(apple)}&status=active`);
    await page.getByRole("cell", { name: apple }).waitFor();
    assert.equal(await page.getByRole("row", { name: new RegExp(apple) }).count(), 1);
    await page.goto(`${baseUrl}/productos?q=${encodeURIComponent(apple)}&status=archived`);
    await page.getByText("No hay productos para estos filtros.", { exact: false }).waitFor();

    const machine = await prisma.productionMachine.findFirstOrThrow({ where: { name: machineName }, select: { id: true } });
    await page.goto(`${baseUrl}/produccion/nuevo?machine=${machine.id}`);
    await page.getByRole("button", { name: "Ver bandejas" }).click();
    await page.getByLabel("Identificación del ciclo").fill(`Ciclo ${marker}`);
    const cycleBackDialog = page.waitForEvent("dialog").then(async (dialog) => { assert.match(dialog.message(), /cambios sin guardar/); await dialog.dismiss(); });
    await page.evaluate(() => window.history.back());
    await cycleBackDialog;
    assert.match(page.url(), /\/produccion\/nuevo/);
    assert.equal(await page.getByLabel("Identificación del ciclo").inputValue(), `Ciclo ${marker}`);
    await page.getByRole("button", { name: "Agregar producto" }).click();
    const productDialog = page.getByRole("dialog", { name: "Agregar producto o variante" });
    await productDialog.getByLabel("Producto", { exact: true }).fill(`Pomelo ${marker}`);
    await productDialog.getByRole("button", { name: "Agregar al catálogo" }).click();
    await productDialog.waitFor({ state: "hidden" });
    await page.waitForFunction((name) => Array.from(document.querySelectorAll('select[aria-label="Producto de bandeja 1"] option')).some((option) => option.textContent?.includes(name)), `Pomelo ${marker}`);
    assert.equal(await page.getByLabel("Identificación del ciclo").inputValue(), `Ciclo ${marker}`);
    await page.getByLabel("Producto de bandeja 1", { exact: true }).selectOption({ label: `${orange} · Con azúcar` });
    await page.getByLabel("Producto de bandeja 2", { exact: true }).selectOption({ label: `${orange} · Con azúcar` });
    await page.getByLabel("Producto de bandeja 3", { exact: true }).selectOption({ label: apple });
    await page.getByLabel("Agrupar bandeja 1", { exact: true }).check();
    await page.getByLabel("Agrupar bandeja 2", { exact: true }).check();
    await page.getByRole("button", { name: "Agrupar selección" }).click();
    await page.getByLabel("Kilos del grupo 1, 2").fill("0.8751");
    await page.getByLabel("Kilos de bandeja 3").fill("0");
    await page.getByRole("button", { name: "Guardar ciclo finalizado" }).click();
    await page.getByRole("alert").filter({ hasText: "tres decimales" }).waitFor();
    assert.match(await page.evaluate(() => document.activeElement?.textContent ?? ""), /tres decimales/);
    await page.getByLabel("Kilos del grupo 1, 2").fill("0.875");
    await page.getByRole("button", { name: "Guardar ciclo finalizado" }).click();
    await page.waitForURL(/\/produccion\/[0-9a-f-]{36}(?:\?.*)?$/);
    const cycleId = new URL(page.url()).pathname.split("/").at(-1)!;
    await page.getByText("Total registrado: 0.875 kg").waitFor();
    await page.getByRole("button", { name: "Pantalla completa", exact: true }).waitFor();
    await page.getByRole("checkbox", { name: "Mostrar tu equipo" }).check();
    await page.waitForTimeout(1000);
    await mkdir("tmp", { recursive: true });
    await page.screenshot({ path: "tmp/qa-production-3d-v2.png", fullPage: true });
    const canvas = page.locator("canvas");
    await canvas.scrollIntoViewIfNeeded();
    const bounds = await canvas.boundingBox();
    assert.ok(bounds);
    await page.mouse.click(bounds.x + bounds.width * 0.45, bounds.y + bounds.height * 0.36);
    const selectedFrom3d = await page.getByRole("heading", { name: /^Bandeja #/ }).textContent();
    assert.notEqual(selectedFrom3d, "Bandeja #1");
    await page.getByText("Piezas visibles", { exact: true }).click();
    await page.getByRole("checkbox", { name: "Puerta abierta" }).uncheck();
    await page.getByRole("checkbox", { name: "Puerta abierta" }).check();
    await page.getByRole("button", { name: "Seleccionar bandeja 3" }).click();
    await page.getByRole("heading", { name: "Bandeja #3" }).waitFor();
    await page.getByRole("button", { name: "Seleccionar bandeja 2" }).focus();
    await page.keyboard.press("Enter");
    await page.getByRole("heading", { name: "Bandeja #2" }).waitFor();
    await canvas.evaluate((element) => element.dispatchEvent(new Event("webglcontextlost", { cancelable: true })));
    await page.getByText("El 3D se interrumpió. Podés seguir desde la vista de bandejas.").waitFor();
    await page.goto(`${baseUrl}/produccion?machine=${machine.id}&month=2026-10`);
    await page.getByRole("heading", { name: "Dashboard de producción" }).waitFor();
    await page.getByRole("link", { name: `Ciclo ${marker}` }).waitFor();
    await page.getByText("0.875 kg", { exact: true }).first().waitFor();
    await page.getByRole("link", { name: "Comparar", exact: true }).click();
    await page.waitForURL((url) => url.searchParams.get("first") === cycleId);
    await page.getByRole("link", { name: `Ciclo ${marker}` }).click();
    await page.waitForURL(/\/produccion\/[0-9a-f-]{36}(?:\?.*)?$/);
    await page.getByRole("button", { name: "Pantalla completa", exact: true }).waitFor();
    await page.setViewportSize({ width: 375, height: 812 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.getByRole("button", { name: "Ver bandejas" }).click();
    await page.getByLabel("Qué hay en esta bandeja").waitFor();
    await page.getByRole("button", { name: "Seleccionar bandeja vacía 4" }).focus();
    await page.keyboard.press("Enter");
    await page.getByRole("heading", { name: "Bandeja #4" }).waitFor();
    await page.screenshot({ path: "tmp/qa-production-mobile-v2.png", fullPage: true });
    await page.setViewportSize({ width: 768, height: 1024 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.screenshot({ path: "tmp/qa-production-tablet-v2.png", fullPage: true });
    await page.setViewportSize({ width: 375, height: 812 });
    await page.getByRole("button", { name: "Editar registro" }).click();
    await page.getByLabel("Observaciones (opcional)").fill("Edición QA sin guardar");
    page.once("dialog", (dialog) => void dialog.dismiss());
    await page.getByRole("navigation", { name: "Secciones de producción" }).getByRole("link", { name: "Dashboard" }).click();
    assert.match(page.url(), /\/produccion\/[0-9a-f-]{36}/);
    await page.getByLabel("Observaciones (opcional)").fill("");
    await page.getByRole("navigation", { name: "Secciones de producción" }).getByRole("link", { name: "Dashboard" }).click();
    await page.waitForURL(/\/produccion\?[^#]*machine=/);
    assert.equal(new URL(page.url()).searchParams.get("month"), "2026-10");
    assert.equal(new URL(page.url()).searchParams.get("machine"), machine.id);

    await page.goto(`${baseUrl}/ventas/nueva`);
    await page.getByRole("navigation", { name: "Tipo de operación" }).getByRole("link", { name: "Muestra" }).click();
    await page.waitForURL("**/muestras/nueva");
    await page.getByLabel("Destinatario").fill(`Destinatario ${marker}`);
    await page.getByLabel("Producto del catálogo").selectOption("manual");
    await page.getByLabel("Nombre del producto").fill(orange);
    await page.getByLabel("Variante (opcional)").fill("Con azúcar");
    await page.getByLabel("Cantidad").fill("0.125");
    await page.getByLabel("Unidad").fill("kg");
    await page.getByLabel("Estado").selectOption("delivered");
    const sampleBackDialog = page.waitForEvent("dialog").then(async (dialog) => { assert.match(dialog.message(), /muestra sin guardar/); await dialog.dismiss(); });
    await page.evaluate(() => window.history.back());
    await sampleBackDialog;
    assert.match(page.url(), /\/muestras\/nueva/);
    assert.equal(await page.getByLabel("Destinatario").inputValue(), `Destinatario ${marker}`);
    await page.getByRole("button", { name: "Registrar muestra" }).click();
    await page.waitForURL(/\/muestras\/[0-9a-f-]{36}$/);
    const noWebgl = await context.newPage();
    await noWebgl.addInitScript(() => {
      const original = HTMLCanvasElement.prototype.getContext;
      HTMLCanvasElement.prototype.getContext = function (this: HTMLCanvasElement, type, ...args) {
        if (type === "webgl" || type === "webgl2") return null;
        return original.call(this, type, ...args);
      } as typeof HTMLCanvasElement.prototype.getContext;
    });
    await noWebgl.goto(`${baseUrl}/produccion/${cycleId}`);
    await noWebgl.getByText("Este dispositivo no admite 3D.", { exact: false }).waitFor();
    await noWebgl.getByLabel("Producto de bandeja 1", { exact: true }).waitFor();
    await noWebgl.close();
    const savedSampleUrl = page.url();
    await page.goto(`${baseUrl}/muestras/nueva`);
    await page.getByLabel("Destinatario").fill(`Borrador ${marker}`);
    const leaveDraftDialog = page.waitForEvent("dialog").then(async (dialog) => { assert.match(dialog.message(), /muestra sin guardar/); await dialog.accept(); });
    await page.evaluate(() => window.history.back());
    await leaveDraftDialog;
    await page.waitForURL(savedSampleUrl);
    assert.equal(await prisma.sale.count(), salesBefore);
    assert.deepEqual(errors, []);
    process.stdout.write("Máquinas, catálogo, ciclo agrupado, 3D, tabla móvil y muestra: navegador correcto.\n");
  } finally {
    await context.close();
    await browser.close();
    if (actorId) {
      const audits = await prisma.auditEvent.findMany({ where: { actorUserId: actorId }, select: { entityType: true, entityId: true } });
      await prisma.productionTray.deleteMany({ where: { cycle: { createdById: actorId } } });
      await prisma.productionResult.deleteMany({ where: { cycle: { createdById: actorId } } });
      await prisma.productionCycle.deleteMany({ where: { createdById: actorId } });
      await prisma.productionMachine.deleteMany({ where: { id: { in: audits.filter((audit) => audit.entityType === "production_machine").map((audit) => audit.entityId) } } });
      await prisma.sampleLine.deleteMany({ where: { sample: { createdById: actorId } } });
      await prisma.sample.deleteMany({ where: { createdById: actorId } });
      await prisma.product.deleteMany({ where: { id: { in: audits.filter((audit) => audit.entityType === "product").map((audit) => audit.entityId) } } });
      await prisma.auditEvent.deleteMany({ where: { actorUserId: actorId } });
      await prisma.user.deleteMany({ where: { id: actorId } });
    }
    await prisma.$disconnect();
  }
}

main().catch((error) => { process.stderr.write(`${error.stack ?? error}\n`); process.exitCode = 1; });
